from .base import BaseProvider
import logging
logger = logging.getLogger(__name__)
class MockProvider(BaseProvider):
    provider_name = "mock"
    def __init__(self):
        self.model = "mock-dev-mode"
    def generate(self, prompt, system_prompt=None, **kwargs):
        cur = kwargs.get("curriculum", "CBC/CBE")
        grade = kwargs.get("grade_level", "")
        mode = kwargs.get("mode", "learner")
        if mode == "teacher":
            t = kwargs.get("topic", "the topic")
            a = kwargs.get("artifact_type", "lesson plan")
            return (f"# {a.replace('_',' ').title()}: {t} ({grade})\n"
                    f"Curriculum: {cur}\n\n"
                    f"## Learning Outcomes\n"
                    f"By the end of this {a}, the learner will:\n"
                    f"1. Explain {t} using correct scientific terminology.\n"
                    f"2. Apply knowledge of {t} to a real-life situation.\n"
                    f"3. Demonstrate the {cur} core competencies of communication and critical thinking.\n\n"
                    f"## Introduction (5 min)\n"
                    f"Engage learners with a question about {t} drawn from their daily experience.\n\n"
                    f"## Main Activity (25 min)\n"
                    f"Guided exploration of {t} using the school's approved resource materials.\n\n"
                    f"## Assessment (10 min)\n"
                    f"Formative check: two short questions on {t}, marked against a {cur} rubric.\n\n"
                    f"_Generated by JIFUNZE AI Teacher Studio · provider: mock-dev-mode_")
        return (f"Great question! Based on your school's approved materials for {grade or 'your grade'} "
                f"({cur} curriculum):\n\n{prompt[:300]}\n\n"
                f"In {cur} terms, the key competency here is understanding the process and being able to "
                f"explain it in your own words.\n\n"
                f"Would you like an example or a practice question? "
                f"(Note: this response is grounded in the cited school resources below.)")
