import os
import logging
from django.conf import settings
logger = logging.getLogger(__name__)
class AIGateway:
    """
    Provider-independent AI gateway for JIFUNZE AI.
    Handles prompt formatting, provider routing, and source grounding.
    """
    def __init__(self):
        self.provider = getattr(settings, 'AI_PROVIDER', 'none')
        self.model = getattr(settings, 'AI_MODEL', 'llama3')
        self.api_key = getattr(settings, 'AI_API_KEY', '')
    def generate_learning_response(self, user_prompt: str, context_chunks: list) -> dict:
        """
        Generates a learning response grounded in provided document chunks.
        Returns: {"content": str, "provider": str, "uncertainty_flag": bool}
        """
        context_text = "\n\n".join([chunk.chunk_text for chunk in context_chunks]) if context_chunks else "No specific school resources provided."
        system_prompt = f"""You are JIFUNZE AI, a helpful, transparent, and privacy-conscious educational assistant for African schools.
        Answer the student's question based PRIMARILY on the provided context from their school's resources.
        If the context does not contain the answer, say: 'I couldn't find this specific information in your school's uploaded resources, but generally...' and provide a safe, general educational answer.
        Keep the tone encouraging and age-appropriate.
        CONTEXT:
        {context_text}
        """
        if self.provider == 'none' or not self.api_key:
            # SMART MOCK MODE: Allows immediate UI/UX development without API costs
            logger.info("Using Mock AI Provider for development")
            mock_response = self._generate_mock_response(user_prompt, context_text)
            return {
                "content": mock_response,
                "provider": "mock_dev_mode",
                "uncertainty_flag": False
            }
        # TODO: Add real provider adapters here (e.g., OpenAI, Anthropic, Ollama)
        # Example: return self._call_openai(system_prompt, user_prompt)
        return {
            "content": "AI Provider is configured but not yet implemented in this sprint.",
            "provider": self.provider,
            "uncertainty_flag": True
        }
